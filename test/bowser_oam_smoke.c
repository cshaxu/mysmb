#include "game/game.h"
#include "game/objects.h"

static int bad(const struct mysmb_game *g, mysmb_u16 a, mysmb_u8 v)
{
    return g->ram[a] == v ? 0 : 1;
}

int main(void)
{
    struct mysmb_game g;
    mysmb_game_initialize_memory(&g, 0xfeU);
    g.ram[0x000fU]=1U; g.ram[0x0016U]=45U; g.ram[0x001eU]=0U; g.ram[0x0046U]=2U; g.ram[0x0363U]=0U;
    g.ram[0x0087U]=0x40U; g.ram[0x00cfU]=0x50U; g.ram[0x071aU]=0U; g.ram[0x071cU]=0U; g.ram[0x071bU]=1U; g.ram[0x071dU]=0U; g.ram[0x06e5U]=0x20U;
    g.ram[0x03eeU]=0U; g.ram[0x06ecU]=0x60U; g.ram[0x06cfU]=1U; g.ram[0x06e6U]=0x60U;
    mysmb_objects_draw_bowsers(&g);
    if (bad(&g,0x0220U,0xf8U)||bad(&g,0x0221U,0xbeU)||bad(&g,0x0222U,0x41U)||
        bad(&g,0x0223U,0x40U)||bad(&g,0x0225U,0xbfU)||bad(&g,0x0229U,0xc0U)||
        bad(&g,0x0231U,0xfcU)||bad(&g,0x0260U,0xf8U)||bad(&g,0x0261U,0xc3U)||
        bad(&g,0x0269U,0xc5U)||bad(&g,0x0271U,0xc7U)||bad(&g,0x0263U,0x50U)) return 1;
    g.ram[0x0363U]=0x81U; g.ram[0x001eU]=0x20U; mysmb_objects_draw_bowsers(&g);
    if (bad(&g,0x0221U,0xfcU)||bad(&g,0x0231U,0xbeU)||bad(&g,0x0222U,0xc1U)||
        bad(&g,0x0260U,0xf8U)||bad(&g,0x0261U,0xcbU)||bad(&g,0x0271U,0xc3U)||
        bad(&g,0x0262U,0xc1U)) return 2;
    return 0;
}
