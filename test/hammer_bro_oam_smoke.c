#include "game/game.h"
#include "game/objects.h"

static int same(const struct mysmb_game *g,const mysmb_u8 *v)
{
    mysmb_u8 i;
    for(i=0U;i<24U;++i)if(g->ram[0x0220U+i]!=v[i])return 0;
    return 1;
}

static void setup(struct mysmb_game *g)
{
    mysmb_game_initialize_memory(g,0U);g->ram[0x071dU]=0xf0U;g->ram[0x000fU]=1U;
    g->ram[0x0016U]=5U;g->ram[0x0046U]=1U;g->ram[0x0087U]=0x40U;
    g->ram[0x00cfU]=0x50U;g->ram[0x06e5U]=0x20U;
}

int main(void)
{
    static const mysmb_u8 normal[24]={
        0x50U,0x7dU,1U,0x40U,0x50U,0x7cU,1U,0x48U,
        0x58U,0xd1U,1U,0x40U,0x58U,0x8cU,1U,0x48U,
        0x60U,0xd3U,1U,0x40U,0x60U,0xd2U,1U,0x48U};
    static const mysmb_u8 throwing[24]={
        0x50U,0xd4U,0x41U,0x40U,0x50U,0xd5U,0x41U,0x48U,
        0x58U,0xe2U,0x41U,0x40U,0x58U,0xe3U,0x41U,0x48U,
        0x60U,0xd2U,0x41U,0x40U,0x60U,0xd3U,0x41U,0x48U};
    static const mysmb_u8 defeated[24]={
        0x50U,0xd3U,0x81U,0x40U,0x50U,0xd2U,0x81U,0x48U,
        0x58U,0xd1U,0x81U,0x40U,0x58U,0x8cU,0x81U,0x48U,
        0x60U,0x7dU,0x81U,0x40U,0x60U,0x7cU,0x81U,0x48U};
    struct mysmb_game g;
    setup(&g);g.ram[0x0009U]=8U;
    if(mysmb_objects_draw_hammer_bro(&g,0U)==0U||same(&g,normal)==0)return 1;
    setup(&g);g.ram[0x001eU]=8U;g.ram[0x0046U]=2U;g.ram[0x0009U]=8U;
    mysmb_objects_draw_hammer_bro(&g,0U);
    if(same(&g,throwing)==0)return 2;
    setup(&g);g.ram[0x001eU]=0x20U;g.ram[0x0009U]=8U;
    mysmb_objects_draw_hammer_bro(&g,0U);
    if(same(&g,defeated)==0)return 3;
    return 0;
}